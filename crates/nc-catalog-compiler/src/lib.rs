//! Reads `catalog/` and produces the crates that carry it.
//!
//! **The rule the whole thing exists for** (`NOCTUA.md §15.2`): a notification,
//! email, error, limit, command, log event or capability **that is not in the
//! catalog does not exist.** There is no ad-hoc path. Sending a notification takes a
//! generated typed handle, not a string, so one that no longer exists is a
//! compile error, and one that exists is documented from the same source once
//! `cargo xtask docs` writes the developer surfaces.
//!
//! **This crate computes nothing.** Values arrive validated from `load` and are
//! formatted. Anything that decides something belongs beside the data it decides
//! about, not in the emitter — the same split `noctua-design` draws, for the
//! same reason: an emitter that computes is an emitter whose output cannot be
//! predicted from its input.
//!
//! **Production is separated from the write.** [`compile`] returns files in
//! memory and touches nothing; writing them is the caller's, and comparing them
//! against disk is what `cargo xtask check` does. That separation is the only
//! reason the drift check means anything — a check that regenerates before
//! comparing reports "in sync" immediately after a hand edit, which
//! `noctua-colors` shipped for a milestone.

