/// One file the compiler produced.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EmittedFile {
    /// Path relative to the repository root, using forward slashes.
    pub path: String,
    /// Complete file contents.
    pub contents: String,
}

impl EmittedFile {
    /// A file at `path` holding `contents`.
    #[must_use]
    pub fn new(path: impl Into<String>, contents: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            contents: contents.into(),
        }
    }
}

/// The command that regenerates everything this crate writes.
pub const REGENERATE: &str = "cargo xtask build";

/// The sentence that marks a file as generated.
///
/// It is also the exemption sentinel every source gate checks for: a gate that
/// judged generated output would be judging the emitter's formatting, one file
/// removed from anything a developer can fix.
pub const GENERATED: &str = "Generated by nc-catalog-compiler — do not edit.";

/// How a language spells a comment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommentStyle {
    /// `//!` for Rust, `#` for TOML — whatever the marker is.
    Line(&'static str),
}

/// The header every generated file carries.
///
/// It names its source and the command that rewrites it, and **carries no
/// version and no hash**: either would rewrite every generated file on every
/// release and bury a one-line change in a diff nobody can read.
#[must_use]
pub fn header(comment: CommentStyle, source: &str) -> String {
    let lines = [
        GENERATED.to_owned(),
        format!("Source: {source}"),
        format!("Regenerate: {REGENERATE}"),
        String::new(),
        "Edits to this file will be overwritten. Change the catalog instead.".to_owned(),
    ];
    let CommentStyle::Line(marker) = comment;
    let mut out = String::new();
    for line in lines {
        if line.is_empty() {
            out.push_str(marker);
            out.push('\n');
        } else {
            out.push_str(marker);
            out.push(' ');
            out.push_str(&line);
            out.push('\n');
        }
    }
    out
}

/// What one compilation produced.
#[derive(Debug, Clone)]
pub struct Compiled {
    /// The validated catalog.
    pub catalog: model::Catalog,
    /// Generated source, in path order. Written by `build`, compared against
    /// disk by `check`.
    pub files: Vec<EmittedFile>,
    /// The reservation ledger.
    ///
    /// **Deliberately not one of `files`.** As one, the drift check would
    /// compare it against output derived from it — so a hand edit would ratify
    /// itself and `check` report "in sync". It is verified instead by
    /// being *read* during compilation: its checksum has to match its contents,
    /// and its contents have to reconcile with `catalog/errors.toml`. Those are
    /// two independent files, which is what a check needs.
    pub ledger: EmittedFile,
}

/// Reads the catalog and returns everything a build would write.
///
/// `bootstrap` says whether a ledger nothing vouches for may be accepted.
/// `cargo xtask check` always passes [`ledger::Bootstrap::Refuse`]; only
/// `cargo xtask build --reserve` passes the other.
///
/// Touches nothing on disk beyond reading.
///
/// # Errors
///
/// Returns every problem found — a malformed registry, a missing message key, a
/// renumbered error code, an edited ledger — located and sorted, rather than the
/// first.
pub fn compile(root: &Path, bootstrap: ledger::Bootstrap) -> Result<Compiled, Vec<Problem>> {
    // **Both classes, not the first one found.** Returning on `load`'s
    // problems would make a catalog with an i18n defect *and* a renumbered code
    // report only the i18n one — while this function's own doc promises "every
    // problem found … rather than the first". Reproduced that way: repointing a
    // code's message key at a name no locale declares reports
    // `dangling-message-key`, and the `code-repointed` that is equally true is
    // never computed.
    //
    // The catalog `load` returns alongside its problems is best-effort, which is
    // exactly what the ledger needs to say anything useful about the codes in
    // it — and nothing is written while any problem stands.
    let (catalog, mut problems) = load::load(root);

    // **Pushed, not `?`-returned, and it says what `load` says.** A *fresh*
    // vector holding one problem, returned three lines under a comment promising
    // "every problem found … rather than the first", would discard every defect
    // `load` has already reported. And a sentence such as "it was read a moment
    // ago, so something changed the tree mid-build" is never true: `load` opens
    // this file first, so an absent or unreadable one has already failed there.
    // Measured that way with the file removed and a locale key also removed:
    // one problem, the wrong sentence, and the locale defect gone.
    //
    // Such a reader is sent to look for a concurrent writer that does not
    // exist, which is worse than silence — `AGENTS.md` calls a diagnostic a set
    // of instructions, and every part of it either true where the reader stands
    // or worse than nothing.
    // **`load` has already said this, so nothing is said twice.** Pushing a
    // diagnostic `load::read` builds word for word — same file, same sentence,
    // same fix, same check name — makes a missing registry print it twice:
    //
    // ```text
    // error catalog/errors.toml — could not be read: No such file or directory (os error 2)
    // error catalog/errors.toml — could not be read: No such file or directory (os error 2)
    // error the catalog has 2 problem(s)
    // ```
    //
    // And a case asserting `problems.len() > 1` under a message about a
    // *locale* defect surviving passes on the duplicate while that defect really
    // is gone, because `load` returns the moment a registry cannot be read and
    // its i18n checks never run.
    //
    // The sort happens here too, so the one path that returns several problems
    // from this exit returns them ordered like every other.
    let Ok(errors_text) = std::fs::read_to_string(root.join("catalog/errors.toml")) else {
        problems.sort_by(|a, b| (&a.file, a.line).cmp(&(&b.file, b.line)));
        return Err(problems);
    };
    // A catalog that could not be assembled at all — an unreadable or
    // unparseable registry — leaves nothing for the ledger to reconcile, and
    // that is the one case where the first problem really is the only one that
    // can be computed.
    let next = match (catalog.as_ref(), ledger::read(root, bootstrap)) {
        (Some(catalog), Ok(reserved)) => {
            match ledger::reconcile(catalog, &reserved, &errors_text) {
                Ok(next) => Some(next),
                Err(found) => {
                    problems.extend(found);
                    None
                }
            }
        }
        (_, Err(problem)) => {
            problems.push(problem);
            None
        }
        (None, Ok(_)) => None,
    };
    let (Some(catalog), Some(next)) = (catalog, next) else {
        problems.sort_by(|a, b| (&a.file, a.line).cmp(&(&b.file, b.line)));
        return Err(problems);
    };
    if !problems.is_empty() {
        problems.sort_by(|a, b| (&a.file, a.line).cmp(&(&b.file, b.line)));
        return Err(problems);
    }

    let mut files = emit::all(&catalog);
    // The developer surfaces (`§15.3`), emitted through the same list as the
    // generated Rust — which costs nothing and buys drift, staleness and
    // determinism for the documentation as well. A verb that wrote Markdown its
    // own way would be a second generation pipeline with none of them.
    files.extend(docs::all(&catalog));
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(Compiled {
        catalog,
        files,
        ledger: EmittedFile::new(ledger::PATH, ledger::render(&next)),
    })
}

