fn parameters(params: &[String]) -> String {
    if params.is_empty() {
        "none".to_owned()
    } else {
        params
            .iter()
            .map(|param| format!("`{{{param}}}`"))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

/// One table of every message an entry carries, a column per locale.
fn messages(catalog: &Catalog, out: &mut String, keys: &[(&str, &String)]) {
    let tags = tags(catalog);
    out.push_str("| | Key |");
    for tag in &tags {
        let _ = write!(out, " {tag} |");
    }
    out.push_str("\n|---|---|");
    for _ in &tags {
        out.push_str("---|");
    }
    out.push('\n');
    for (label, key) in keys {
        let _ = write!(out, "| {label} | `{}` |", cell(key));
        for tag in &tags {
            let _ = write!(out, " {} |", sentence(catalog, key, tag));
        }
        out.push('\n');
    }
    out.push('\n');
}

/// Whose rows a table's `Maximum rows` counts, as the page says it.
///
/// **A refusing writer can count one owner's rows**, and without this the page
/// publishes such a number as the table's own: `store_entries`' writer refuses a plugin's
/// new key at that plugin's count in its realm, so the table holds the number
/// for every plugin installed in every realm. A table with no number counts
/// nothing.
const fn what_a_limit_counts(max_rows: Option<u64>, per: Option<Owner>) -> &'static str {
    match (max_rows, per) {
        (None, _) => "—",
        (Some(_), None) => "the whole table",
        (Some(_), Some(owner)) => owner.counted_over(),
    }
}

/// What the limits page opens with, ahead of its tables.
///
/// Its own constant because `limits` crossed clippy's line limit with it inline.
///
/// **Where each table's bound comes from is named, not counted**: a number in
/// emitted prose is a number nothing recomputes when a table is added.
const LIMITS_OPENING: &str = "Every bound this catalog declares. A table that can grow \
     without bound and has no \
     entry here **fails the build** — that gate is what makes this a policy rather than \
     a habit (`§15.8`).\n\n\
     **Declared is not the same as enforced, and each part of this page has its \
     own answer.** The kernel holds every plugin to every bound under **Kernel**. \
     A `local` table is held by `crates/nc-local`, which refuses a unit at a \
     `refuse-at-limit` bound as it commits, and by the pruner, which \
     `Kernel::pump` and the `limits.prune` command run over the local database — \
     and nothing in this tree calls either on a timer yet. Nothing here prunes a \
     `server` table, and there is no rate limiter and no key derivation, as their \
     own sections say. This paragraph said *nothing on this page has a runner* \
     while every `refuse-at-limit` bound under **Tables** was refused at already. \
     One thing is \
     enforced and is not a number — `access_records`' ordering column, which a \
     trigger assigns (`migrations/0006_access_records_orders_by_insertion.sql`), \
     because a bound that orders by a value a caller writes is a bound a caller \
     can move.\n\n\
     **A table is in one of two databases**, and its `Database` column says which: \
     `server` is PostgreSQL, built by `migrations/`, and `local` is the SQLite file \
     on the user's own machine, built by `local-migrations/`. A table whose \
     strategy is `refuse-at-limit` is one whose oldest rows are not the pruner's to \
     take — user state, what a plugin keeps or a blob a unit pinned, or a unit's images \
     and notes, which an undo needs whole and which leave with their unit — so nothing \
     prunes it by its own count: its `Maximum rows` is where its writer refuses a new \
     row, and the refusal is the bound. `Counted over` says whose rows that number \
     counts: a table counted over each plugin's rows in each realm holds that many for \
     every plugin installed in every realm the machine serves, and one counted over \
     each unit's rows that many for every unit the \
     store holds, so its own size is the number times its owners, not the number.\n\n\
     Each table below says where its own bound comes from, in its own last column \
     or in the prose above it.";

fn limits(catalog: &Catalog) -> String {
    let mut out = header("Limits", "catalog/limits.toml", LIMITS_OPENING);
    out.push_str(
        "## Tables\n\n| Table | Database | Strategy | Ordered by | Maximum rows | Counted \
         over | Prune batch (rows per run) | Why it has no number |\n",
    );
    out.push_str("|---|---|---|---|---|---|---|---|\n");
    for (name, table) in &catalog.limits.tables {
        // **Escaped, like every other value on this row.** A table's key is not
        // put through `load::identifier()` anywhere — `check_tables` never
        // touches it — so a bar in it ends its own cell and the row is read one
        // column wide of the header. The exclusion list in
        // `a_bar_in_a_registry_value_does_not_end_its_cell` must not excuse this
        // surface or the store's beside it on the ground that both *are*
        // identifier-checked, which is false of both; with either excused and
        // unescaped, adding it to that list's sweep turns it red at once.
        let name = cell(name);
        let _ = writeln!(
            out,
            "| `{name}` | `{}` | `{}` | `{}` | {} | {} | {} | {} |",
            table.database.written(),
            table.strategy.written(),
            cell(&table.order_by),
            // **Not "the policy pack".** That is the specific false claim: it
            // names a live mechanism, and `catalog/limits.toml`'s own
            // `pack_reason` says no pack declares a retention and the table
            // grows without limit — *"a gap with a date on it rather than a
            // bound"*. The field is parsed, required, refused where it does not
            // belong and gate-tested, and it is published here, because it is
            // the one sentence that says this is not a bound.
            table
                .max_rows
                .map_or_else(|| "none".to_owned(), |rows| rows.to_string()),
            what_a_limit_counts(table.max_rows, table.per),
            table
                .prune_batch
                .map_or_else(|| "—".to_owned(), |batch| batch.to_string()),
            table
                .pack_reason
                .as_deref()
                .map_or_else(|| "—".to_owned(), |why| cell(why.trim()))
        );
    }

    out.push_str("\n## Stores outside PostgreSQL\n\n");
    out.push_str("| Store | Retention (days) | Maximum disk | Enforced by |\n|---|---|---|---|\n");
    for (name, store) in &catalog.limits.stores {
        // The other half of the same hole; see the table loop above.
        let name = cell(name);
        let _ = writeln!(
            out,
            "| `{name}` | {} | {} | {} |",
            store.retention_days,
            // **With its unit.** A bare `8589934592` beside a column headed
            // `Retention (days)` puts the only two numbers on the row in
            // different units with only one of them saying which.
            // `docker-compose.yml` writes the same limit as `8GiB`.
            in_bytes(store.max_disk_bytes),
            cell(&store.enforced_by)
        );
    }

    out.push_str("\n## Key derivation\n\n");
    // **The algorithm, which the table never named.** A table of Memory,
    // Iterations and Parallelism with no KDF beside it cannot be audited or
    // reproduced — and `Argon2Id` is the type these numbers are parsed into.
    out.push_str(
        "Argon2id, per `§10.5` and `§10.6` — the sections `catalog/limits.toml` itself \
         cites over these entries. (This line said `§15.5`, which is rate limits: the \
         page named a section about a different subject, eleven lines from a second, \
         independently written mention of the same algorithm.) **Nothing derives a key \
         yet**: there is no `argon2` dependency in this tree, and these are the \
         parameters the stage that adds one will read.\n\n",
    );
    // **Every column with its unit, and the memory through the humanizer this
    // file already owns.** `Output 32` and `Salt 16` are bytes, and a header
    // that says neither leaves a reader assuming bits out by a factor of eight;
    // and `in_bytes` applied to one number on the page with the memory beside
    // it in KiB is one page rendering one figure for people and another for
    // machines.
    // **`Derived key` is wrong for the password row**, which produces a
    // verifier rather than a key: nothing decrypts with it, and calling it a key
    // invites a reader to think something does.
    out.push_str("| Purpose | Memory | Iterations | Parallelism (lanes) | Output | Salt |\n");
    out.push_str("|---|---|---|---|---|---|\n");
    for (purpose, argon) in [
        ("password", catalog.limits.argon2id.password),
        ("device PIN", catalog.limits.argon2id.device_pin),
    ] {
        let _ = writeln!(
            out,
            "| {purpose} | {} | {} | {} | {} | {} |",
            in_bytes(u64::from(argon.memory_kib) * 1024),
            argon.iterations,
            argon.parallelism,
            in_bytes(u64::from(argon.output_length)),
            in_bytes(u64::from(argon.salt_length))
        );
    }

    out.push_str(&rate_limits(catalog));
    out.push_str(&kernel(catalog));
    out
}

/// One kernel limit's value, in the unit it is counted in.
///
/// Bytes through [`in_bytes`], like every other size on the page; anything
/// else with the unit written after it, so no number here is bare but a count.
fn kernel_value(limit: &crate::model::KernelLimit) -> String {
    match (limit.unit, limit.unit.in_words()) {
        (crate::model::Unit::Bytes, _) => in_bytes(limit.value),
        (_, Some(unit)) => format!("{} {unit}", limit.value),
        (_, None) => limit.value.to_string(),
    }
}

