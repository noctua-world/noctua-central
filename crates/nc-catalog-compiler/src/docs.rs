    /// Each unit the reader is shown, at the smallest value that selects it.
    ///
    /// At the boundary, because that is the only place the table's divisors are
    /// visible: `KiB`'s `1 << 10` doubled to `1 << 11` still renders every
    /// larger multiple correctly and simply stops calling a kibibyte a
    /// kibibyte, which no value in the shipped catalog is small enough to show.
    #[test]
    fn every_unit_is_named_at_its_own_boundary() {
        assert_eq!(in_bytes(1 << 10), "1 KiB (1024 bytes)");
        assert_eq!(in_bytes(1 << 20), "1 MiB (1048576 bytes)");
        assert_eq!(in_bytes(1 << 30), "1 GiB (1073741824 bytes)");
        // The largest unit that divides exactly, not the first that fits.
        assert_eq!(in_bytes(3 << 20), "3 MiB (3145728 bytes)");
        // Below the smallest unit, and not a multiple of any of them: the
        // fall-through, which says bytes and says the word.
        assert_eq!(in_bytes(512), "512 bytes");
        assert_eq!(in_bytes(1_500), "1500 bytes");
        assert_eq!(in_bytes(0), "0 bytes");
    }

    /// Every reversibility publishes the answer it means, all three.
    ///
    /// **The third arm is dead on the shipped catalog, so this asserts it.**
    /// `catalog/commands.toml` declares `read` and `write` and no
    /// `irreversible`, so the generated page never carries that sentence and
    /// the drift comparison — the emitter against its own committed output —
    /// is true by construction about it. Without this, the arm given
    /// `"**yes**, the kernel reverses it each time"` here and in the mirror
    /// leaves `check passed`, every verdict line identical.
    ///
    /// So the arm is asked the question its column asks. The published sentence
    /// answers *"can it be undone"*, and for a command a human must confirm
    /// each time the answer is not yes — which is a claim about the sentence
    /// and not a copy of it, so a mirror cannot make it true.
    ///
    /// Exhaustive, so a variant added to `Reversibility` is a compile error
    /// here rather than a row that quietly stops being checked — and asked of
    /// a command of the history and of one that is not, since a `write`
    /// command the kernel runs on the realm itself is one undo stops at.
    #[test]
    fn every_reversibility_publishes_the_answer_it_means() {
        use crate::model::Reversibility;

        for reversibility in [
            Reversibility::Read,
            Reversibility::Write,
            Reversibility::Irreversible,
        ] {
            for the_history in [false, true] {
                let meant = match reversibility {
                    Reversibility::Read => "nothing to undo — it changes nothing",
                    Reversibility::Write if the_history => {
                        "yes, for what the kernel keeps — its `store` writes and the blobs it \
                         made — through `kernel.undo` and `kernel.redo`; a step that left the \
                         machine or cannot be undone, with no compensation registered for it, \
                         is one undo stops at, and a timer it armed or an event it published \
                         stays as it is (§11.5)"
                    }
                    Reversibility::Write => "no — a step that ran it is one undo stops at (§11.5)",
                    Reversibility::Irreversible => {
                        "**no**, and a human confirms it each time (§14.6)"
                    }
                };
                assert_eq!(
                    what_undoing_costs(reversibility, the_history),
                    meant,
                    "`{reversibility:?}` is published as `{}`",
                    what_undoing_costs(reversibility, the_history)
                );
            }
        }

        // And the claim, applied to the arms no step undo takes back reaches:
        // neither a command a human must confirm each time nor one the kernel
        // runs on the realm itself can be published as one this repository can
        // undo.
        for published in [
            what_undoing_costs(Reversibility::Irreversible, false),
            what_undoing_costs(Reversibility::Write, false),
        ] {
            assert!(
                !published.contains("yes"),
                "a command undo stops at is published as `{published}`, and undo stops \
                 at such a command rather than taking it back"
            );
            assert!(
                published.starts_with("**no**") || published.starts_with("no "),
                "a command undo stops at is published as `{published}`, which does not \
                 answer the question the column asks"
            );
        }
        assert_eq!(super::THE_HISTORY, ["kernel.undo", "kernel.redo"]);
    }

    #[test]
    fn nothing_a_translator_can_write_ends_a_cell_early() {
        // A `|` ends a Markdown cell and a line break ends the row, and both
        // arrive from prose somebody writes freely.
        assert_eq!(cell("a | b"), "a \\| b");
        for break_ in ['\n', '\r', '\u{2028}', '\u{2029}'] {
            assert_eq!(
                cell(&format!("a{break_}b")),
                "a b",
                "U+{:04X}",
                break_ as u32
            );
        }

        // **A backslash before the pipe**, which defeats an escape of `|`
        // alone: `C:\` followed by a `|` escapes the backslash rather than the
        // bar, and the bar goes on to end the cell. One more character than the
        // case above.
        assert_eq!(cell("C:\\|drive"), "C:\\\\\\|drive");
        assert_eq!(cell("ends with \\"), "ends with \\\\");

        // And the order: escaping `|` first and `\` after would have escaped the
        // backslashes this function itself added, doubling every bar.
        assert_eq!(cell("a|b"), "a\\|b");

        // Prose with none of them is left exactly as it was written, because a
        // function that rewrote ordinary sentences would be worse than the bug.
        assert_eq!(
            cell("Uma frase comum, com acentuação."),
            "Uma frase comum, com acentuação."
        );
    }
